#!/usr/bin/env python
"""Generate the runtime capability matrix in docs/runtimes.md.

Renders a markdown table (rows = capability dimensions, columns = the six
public runtimes) from the single source of truth
``swarmline.runtime.capabilities._CAPABILITIES_BY_RUNTIME`` and splices it
between the markers in docs/runtimes.md:

    <!-- BEGIN GENERATED RUNTIME MATRIX -->
    <!-- END GENERATED RUNTIME MATRIX -->

Usage:
    python scripts/gen_runtime_matrix.py           # rewrite docs section
    python scripts/gen_runtime_matrix.py --check   # exit 1 if docs are stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from swarmline.runtime.capabilities import (
    CAPABILITY_DIMENSIONS,
    get_runtime_capabilities,
)

#: Public Agent API runtimes, in docs "Comparison" order. ``headless`` is
#: internal and intentionally excluded.
PUBLIC_RUNTIMES: tuple[str, ...] = (
    "thin",
    "claude_sdk",
    "deepagents",
    "cli",
    "openai_agents",
    "pi_sdk",
)

BEGIN_MARKER = "<!-- BEGIN GENERATED RUNTIME MATRIX -->"
END_MARKER = "<!-- END GENERATED RUNTIME MATRIX -->"

_LEVEL_CELL = {"native": "native", "emulated": "emulated", "none": "—"}


def default_docs_path() -> Path:
    """docs/runtimes.md relative to the repository root."""
    return Path(__file__).resolve().parent.parent / "docs" / "runtimes.md"


def render_matrix() -> str:
    """Render the capability matrix as a deterministic markdown table."""
    caps = {name: get_runtime_capabilities(name) for name in PUBLIC_RUNTIMES}

    header = ["Capability", *(f"`{name}`" for name in PUBLIC_RUNTIMES)]
    tiers = ["**Tier**", *(f"**{caps[name].tier}**" for name in PUBLIC_RUNTIMES)]

    lines = [
        "| " + " | ".join(header) + " |",
        "| " + " | ".join(["---"] * len(header)) + " |",
        "| " + " | ".join(tiers) + " |",
    ]
    for dimension in CAPABILITY_DIMENSIONS:
        cells = [_LEVEL_CELL[caps[name].level(dimension)] for name in PUBLIC_RUNTIMES]
        lines.append("| `" + dimension + "` | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_section() -> str:
    """Full generated section, markers included."""
    note = (
        "Levels: **native** — provided by the underlying runtime/SDK, "
        "**emulated** — provided by the Swarmline portable layer, "
        "— — not available. Generated by `scripts/gen_runtime_matrix.py` "
        "from `swarmline.runtime.capabilities` — do not edit by hand. "
        "The table shows each runtime's *potential*; conditional capabilities "
        "are narrowed per configuration by `RuntimeCapabilities.resolve()` "
        "(e.g. `deepagents` native built-ins require a non-portable "
        "`feature_mode`)."
    )
    return f"{BEGIN_MARKER}\n\n{note}\n\n{render_matrix()}\n\n{END_MARKER}"


def _splice(text: str) -> str:
    """Replace the marker-delimited section of *text* with the fresh render."""
    begin = text.index(BEGIN_MARKER)
    end = text.index(END_MARKER)
    if end < begin:
        raise ValueError("END marker precedes BEGIN marker in docs")
    return text[:begin] + render_section() + text[end + len(END_MARKER) :]


def docs_are_current(docs_path: Path | None = None) -> bool:
    """True if the generated section in docs matches the code matrix."""
    path = docs_path or default_docs_path()
    text = path.read_text(encoding="utf-8")
    return _splice(text) == text


def write_docs(docs_path: Path | None = None) -> bool:
    """Rewrite the generated section. Returns True if the file changed."""
    path = docs_path or default_docs_path()
    text = path.read_text(encoding="utf-8")
    updated = _splice(text)
    if updated == text:
        return False
    path.write_text(updated, encoding="utf-8")
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the docs matrix differs from the code matrix",
    )
    parser.add_argument(
        "--docs",
        type=Path,
        default=None,
        help="path to runtimes.md (default: docs/runtimes.md)",
    )
    args = parser.parse_args(argv)

    if args.check:
        if docs_are_current(args.docs):
            print("runtime matrix: docs are up to date")
            return 0
        print(
            "runtime matrix: docs are STALE — run "
            "`python scripts/gen_runtime_matrix.py`",
            file=sys.stderr,
        )
        return 1

    changed = write_docs(args.docs)
    print("runtime matrix: " + ("docs updated" if changed else "already up to date"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
