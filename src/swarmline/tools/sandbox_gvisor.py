"""GVisorSandboxProvider — sandbox isolation via gVisor (runsc).

Implements the swarmline SandboxProvider protocol using gVisor's ``runsc``
OCI-compatible runtime for kernel-level isolation.

Design:
  - Commands are executed inside a running gVisor container via ``runsc exec``.
  - An injectable ``_command_runner`` (Callable[[list[str]], Awaitable[ExecutionResult]])
    allows tests to capture the constructed command without a real gVisor runtime.
  - NetworkPolicy (optional) declares egress rules; retrieve them via
    ``get_network_policy_rules()`` to apply to the container at setup time.
  - Path safety mirrors DockerSandboxProvider: absolute paths and ``..`` traversal
    are blocked before any command is built.

Note: Fly.io (Firecracker) and cloud VM sandbox providers are SEPARATE optional
packages, NOT implemented here. Only the gVisor (runsc) provider ships in core.

REQ-OSS-050: opt-in / additive.
REQ-OSS-051: zero product coupling — no tenant/workspace/AccessContext/
             FastAPI/SQLAlchemy/Lobu.
"""

from __future__ import annotations

import asyncio
import base64
import os
import shlex
from collections.abc import Awaitable, Callable
from dataclasses import dataclass

from swarmline.tools.types import ExecutionResult, SandboxConfig, SandboxViolation

# Shell wrappers that bypass the denied_commands denylist via indirection.
_DENYLIST_WRAPPERS = frozenset({"sh", "bash", "zsh", "ksh", "dash", "fish", "env"})

# Workspace path inside the gVisor container (OCI convention).
_CONTAINER_WORKSPACE = "/workspace"

# Type alias for the injectable command runner.
_CommandRunner = Callable[[list[str]], Awaitable[ExecutionResult]]


@dataclass(frozen=True)
class GVisorConfig:
    """Configuration for the gVisor (runsc) sandbox runtime.

    Args:
        runsc_binary:  Path to the ``runsc`` binary.
        container_id:  OCI container identifier to exec into.
        bundle_dir:    Path to the OCI bundle directory (config.json + rootfs).
        platform:      gVisor platform: ``systrap`` (default, broadest compat),
                       ``kvm`` (hardware acceleration), or ``ptrace`` (legacy).
        network:       gVisor network mode: ``sandbox`` (isolated), ``host``
                       (share host network), or ``none`` (no networking).
        rootless:      Whether to run rootless (no root privileges required).
    """

    runsc_binary: str = "/usr/local/bin/runsc"
    container_id: str = "swarmline-sandbox"
    bundle_dir: str = "/var/run/swarmline/bundle"
    platform: str = "systrap"
    network: str = "sandbox"
    rootless: bool = True


class GVisorSandboxProvider:
    """SandboxProvider backed by gVisor (runsc) kernel-level isolation.

    File operations and command execution are delegated to an injectable
    ``_command_runner``; when None the real ``runsc`` binary is used via
    ``asyncio.create_subprocess_exec``.

    Args:
        config:          swarmline SandboxConfig (denied_commands, timeout, etc.).
        gvisor_config:   GVisor-specific runtime configuration.
        network_policy:  Optional NetworkPolicy; retrieve generated iptables rules
                         via ``get_network_policy_rules()`` to apply at container
                         setup time (not applied automatically — caller decides).
        _command_runner: Injectable async callable for testing.  Receives the full
                         ``runsc exec ...`` command list and must return an
                         ``ExecutionResult``.  When None the real subprocess is used.
    """

    def __init__(
        self,
        config: SandboxConfig,
        gvisor_config: GVisorConfig,
        network_policy: object | None = None,
        *,
        _command_runner: _CommandRunner | None = None,
    ) -> None:
        self._config = config
        self._gconfig = gvisor_config
        self._network_policy = network_policy
        self._runner = _command_runner

    # ------------------------------------------------------------------
    # Network policy
    # ------------------------------------------------------------------

    def get_network_policy_rules(self) -> list[str]:
        """Return the iptables rules generated by the attached NetworkPolicy.

        Returns an empty list when no NetworkPolicy was supplied.  Rules are
        ready to be applied to the container's network namespace at setup time.
        """
        if self._network_policy is None:
            return []
        # Duck-typed to avoid a hard import cycle; NetworkPolicy always has this method.
        fn = getattr(self._network_policy, "to_iptables_rules", None)
        if fn is None:
            return []
        result = fn()
        return list(result)

    # ------------------------------------------------------------------
    # runsc command builder
    # ------------------------------------------------------------------

    def build_runsc_exec(self, argv: list[str]) -> list[str]:
        """Build the ``runsc exec`` command for running *argv* inside the container.

        Structure::

            <runsc_binary> [--platform <p>] [--network <n>] exec <container_id> <argv...>

        Args:
            argv: Command + arguments to execute inside the gVisor container.

        Returns:
            Full command list suitable for passing to subprocess.
        """
        cmd: list[str] = [
            self._gconfig.runsc_binary,
            "--platform",
            self._gconfig.platform,
            "--network",
            self._gconfig.network,
            "exec",
            self._gconfig.container_id,
        ]
        cmd.extend(argv)
        return cmd

    # ------------------------------------------------------------------
    # Path safety (mirrors DockerSandboxProvider)
    # ------------------------------------------------------------------

    @staticmethod
    def _resolve_path(path: str) -> str:
        """Normalise *path* relative to the container workspace, blocking traversal."""
        if os.path.isabs(path):
            raise SandboxViolation(f"Absolute path forbidden: {path}", path=path)
        parts = [p for p in path.split("/") if p]
        if any(part == ".." for part in parts):
            raise SandboxViolation(f"Path traversal forbidden: {path}", path=path)
        return "/".join(parts)

    @staticmethod
    def _validate_glob_pattern(pattern: str) -> None:
        if os.path.isabs(pattern):
            raise SandboxViolation(
                f"Absolute path forbidden in glob: {pattern}", path=pattern
            )
        parts = [p for p in pattern.split("/") if p]
        if any(part == ".." for part in parts):
            raise SandboxViolation(
                f"Path traversal forbidden in glob: {pattern}", path=pattern
            )

    def _parse_command(self, command: str) -> list[str]:
        try:
            argv = shlex.split(command, posix=True)
        except ValueError as exc:
            raise SandboxViolation(f"Invalid command: {command}", path=command) from exc
        if not argv:
            raise SandboxViolation("Empty command forbidden", path=command)
        return argv

    def _check_denied(self, argv: list[str], raw: str) -> None:
        denied = self._config.denied_commands or frozenset()
        cmd_name = os.path.basename(argv[0])
        if cmd_name in _DENYLIST_WRAPPERS:
            raise SandboxViolation(f"Shell wrapper '{cmd_name}' forbidden", path=raw)
        for word in argv:
            name = os.path.basename(word)
            if name in denied:
                raise SandboxViolation(f"Command '{name}' is denied", path=raw)

    # ------------------------------------------------------------------
    # Execution helpers
    # ------------------------------------------------------------------

    async def _run(self, runsc_cmd: list[str]) -> ExecutionResult:
        """Dispatch *runsc_cmd* to the injected runner or real subprocess."""
        if self._runner is not None:
            return await self._runner(runsc_cmd)
        return await self._run_subprocess(runsc_cmd)

    async def _run_subprocess(self, cmd: list[str]) -> ExecutionResult:
        """Execute *cmd* via asyncio subprocess (real gVisor path)."""
        try:
            proc = await asyncio.create_subprocess_exec(
                *cmd,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
            stdout_b, stderr_b = await asyncio.wait_for(
                proc.communicate(),
                timeout=self._config.timeout_seconds,
            )
            return ExecutionResult(
                stdout=stdout_b.decode("utf-8", errors="replace"),
                stderr=stderr_b.decode("utf-8", errors="replace"),
                exit_code=proc.returncode or 0,
                timed_out=False,
            )
        except TimeoutError:
            return ExecutionResult(
                stdout="", stderr="timeout", exit_code=-1, timed_out=True
            )

    # ------------------------------------------------------------------
    # SandboxProvider protocol implementation
    # ------------------------------------------------------------------

    async def read_file(self, path: str) -> str:
        """Read a file from the container workspace via ``runsc exec cat``."""
        safe = self._resolve_path(path)
        full = f"{_CONTAINER_WORKSPACE}/{safe}"
        result = await self._run(self.build_runsc_exec(["cat", full]))
        return result.stdout

    async def write_file(self, path: str, content: str) -> None:
        """Write a file to the container workspace via ``runsc exec python3``."""
        if len(content.encode("utf-8")) > self._config.max_file_size_bytes:
            raise SandboxViolation(
                f"File exceeds limit of {self._config.max_file_size_bytes} bytes",
                path=path,
            )
        safe = self._resolve_path(path)
        full = f"{_CONTAINER_WORKSPACE}/{safe}"
        encoded = base64.b64encode(content.encode("utf-8")).decode("ascii")
        script = (
            "import base64,os,sys;"
            "p=sys.argv[1];d=sys.argv[2];"
            "os.makedirs(os.path.dirname(p),exist_ok=True);"
            "open(p,'wb').write(base64.b64decode(d))"
        )
        await self._run(self.build_runsc_exec(["python3", "-c", script, full, encoded]))

    async def execute(self, command: str) -> ExecutionResult:
        """Execute *command* inside the gVisor container.

        Applies denied_commands checks before dispatching to ``runsc exec``.
        """
        argv = self._parse_command(command)
        self._check_denied(argv, command)
        runsc_cmd = self.build_runsc_exec(argv)
        try:
            return await self._run(runsc_cmd)
        except TimeoutError:
            return ExecutionResult(
                stdout="", stderr="timeout", exit_code=-1, timed_out=True
            )

    async def list_dir(self, path: str = ".") -> list[str]:
        """List files in the container workspace directory via ``runsc exec ls``."""
        safe = self._resolve_path(path) if path != "." else ""
        full = f"{_CONTAINER_WORKSPACE}/{safe}" if safe else _CONTAINER_WORKSPACE
        result = await self._run(self.build_runsc_exec(["ls", full]))
        return [f for f in result.stdout.strip().split("\n") if f]

    async def glob_files(self, pattern: str) -> list[str]:
        """Glob files in the container workspace via ``runsc exec find``."""
        self._validate_glob_pattern(pattern)
        find_cmd = [
            "sh",
            "-c",
            f"cd {shlex.quote(_CONTAINER_WORKSPACE)} "
            f"&& find . -name {shlex.quote(pattern)} -type f | sed 's|^\\./||'",
        ]
        result = await self._run(self.build_runsc_exec(find_cmd))
        return sorted(f for f in result.stdout.strip().split("\n") if f)


__all__ = ["GVisorConfig", "GVisorSandboxProvider"]
